// Writes migrations/0024_bev_dataset_v2026_10_03d.sql from the constants in model.ts (0010, 0015, 0021 and 0022 are frozen earlier versions).
// Run: node --experimental-strip-types scripts/gen-dataset-seed.mjs   (add --check to verify only)
import { readFileSync, writeFileSync } from "node:fs";
import { seedRows, SEED_VERSION } from "../src/lib/navigator/dataset.ts";

const q = (v) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
export function seedSql() {
  const values = seedRows()
    .map((r) => `  (${q(SEED_VERSION)}, ${q(r.key)}, ${r.value}, ${q(r.unit)}, ${q(r.status)}, ${q(r.publisher)}, ${q(r.published_on)}, ${q(r.source_url)}, ${q(r.note)})`)
    .join(",\n");
  return `-- Generated by scripts/gen-dataset-seed.mjs from src/lib/navigator/model.ts. Do not edit by hand.
insert into bev_dataset (dataset_version, key, value, unit, status, publisher, published_on, source_url, note) values
${values}
on conflict (dataset_version, key) do nothing;
`;
}

const file = new URL("../migrations/0024_bev_dataset_v2026_10_03d.sql", import.meta.url);
if (process.argv[1] && import.meta.url === new URL(process.argv[1], "file:").href) {
  if (process.argv.includes("--check")) {
    process.exit(readFileSync(file, "utf8") === seedSql() ? 0 : 1);
  } else writeFileSync(file, seedSql());
}
